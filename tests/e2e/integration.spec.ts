import { expect, test } from "@playwright/test";
import { pdfFixture } from "../fixtures/document-intelligence";
import { createCourse, createCourseWithLesson, createLesson, selectCourseOnPage } from "./helpers";

test("PDF import → index → tutor citation → Lewis edit → save → reload", async ({ page, request }) => {
  test.setTimeout(360_000);
  const errors: string[] = [];
  page.on("pageerror", (error) => errors.push(error.message));
  const { course, lesson } = await createCourseWithLesson(request);
  const alternateLesson = await createLesson(request, course.id, "Practice and applications");
  const otherCourse = await createCourse(request, `BIOL 130 ${Date.now()}`, "Cell biology");
  await createLesson(request, otherCourse.id, "Cell structure");
  await page.goto("/");
  await selectCourseOnPage(page, course.title);
  await expect(page.getByRole("button", { name: "Choose canvas board" })).toBeVisible();
  await page.getByRole("button", { name: "Choose canvas board" }).click();
  await page.getByRole("button", { name: "New board" }).click();
  await page.getByRole("button", { name: "Choose canvas board" }).click();
  await expect(page.locator(".canvas-object")).toHaveCount(0);
  await page.getByRole("button", { name: "Lecture", exact: true }).click();
  const filename = `bonding-${Date.now()}.pdf`;
  await page.locator(".di-file-input").setInputFiles({ name: filename, mimeType: "application/pdf", buffer: Buffer.from(pdfFixture("The carbon dioxide Lewis structure has two double bonds and four nonbonding electrons on each oxygen. The lecture marker is LEWIS-7042.")) });
  await expect(page.getByText("Indexed", { exact: true })).toBeVisible({ timeout: 30_000 });
  const indexed = await request.get(`/api/document-intelligence/search?course=${course.id}&q=LEWIS-7042`);
  const hit = (await indexed.json()).results[0];
  expect(hit).toMatchObject({ filename, unitType: "page", unitNumber: 1 });
  expect((await (await request.get(`/api/document-intelligence/search?course=${otherCourse.id}&q=LEWIS-7042`)).json()).results).toEqual([]);
  const chat = page.getByTestId("copilot-chat-textarea");
  await chat.fill("According to my imported lecture, what is the lecture marker LEWIS-7042 and how many bonds does carbon dioxide have? Cite the page.");
  await chat.press("Enter");
  const citation = page.locator('a[href^="#studyai-citation="]').filter({ hasText: filename }).last();
  await expect(citation).toBeVisible({ timeout: 180_000 });
  await expect(citation).toContainText("page 1");
  expect(decodeURIComponent((await citation.getAttribute("href"))!.split("=").slice(1).join("="))).toBe(hit.sourceRef);
  await expect(page.locator(".copilot-slot")).toContainText(/two double bonds|2 double bonds/i);
  expect((await (await request.get(`/api/document-intelligence/documents/${hit.documentId}?course=${course.id}`)).json()).lessonId).toBe(lesson.id);
  await citation.click();
  const viewer = page.getByRole("dialog", { name: filename });
  await expect(viewer).toBeVisible();
  await expect(page.getByText("Page 1 of 1")).toBeVisible();
  await expect(viewer.locator(".react-pdf__Page__canvas")).toBeVisible({ timeout: 30_000 });
  await viewer.getByRole("button", { name: "Close preview" }).click();
  await page.getByRole("button", { name: "Canvas", exact: true }).click();
  await page.getByRole("button", { name: "Lewis structure", exact: true }).click();
  await page.getByRole("combobox", { name: "Bond order", exact: true }).first().selectOption("1");
  await page.getByRole("spinbutton", { name: "Nonbonding electrons", exact: true }).first().fill("6");
  await page.locator(".canvas-object-editor").getByRole("button", { name: "Done", exact: true }).click();
  await page.getByRole("button", { name: "Collapse canvas tools", exact: true }).click();
  await page.getByRole("button", { name: /^Draw —/ }).click();
  const canvasBox = (await page.locator(".canvas-board").boundingBox())!;
  await page.mouse.move(canvasBox.x + 35, canvasBox.y + 100);
  await page.mouse.down();
  await page.mouse.move(canvasBox.x + 110, canvasBox.y + 135, { steps: 6 });
  await page.mouse.up();
  await expect(page.locator(".top-actions .saved")).toHaveText("All changes saved");
  const savedCanvas = async () => {
    const boards = await (await request.get(`/api/canvases?course=${course.id}&lesson=${lesson.id}`)).json();
    const row = await (await request.get(`/api/canvases/${boards[0].id}?course=${course.id}&lesson=${lesson.id}`)).json();
    return JSON.parse(row.document);
  };
  const shapes = (document: { snapshot: { document: { store: Record<string, { typeName?: string }> } } }) => Object.entries(document.snapshot.document.store).filter(([, record]) => record.typeName === "shape");
  await expect.poll(async () => shapes(await savedCanvas()).length).toBeGreaterThan(0);
  const drawing = shapes(await savedCanvas());
  await chat.fill('Read the molecule on my active canvas and the imported carbon dioxide lecture. Use propose_canvas_edit with the parent molecule objectId. Use atomEdits to set the first oxygen nonbondingElectrons to 4 and bondEdits to set its bond order to 2. Also change the molecule name to "Tutor reviewed CO2". Preserve every atom, bond and resonance ID and all other data. Call the tool to propose these changes for my review.');
  await chat.press("Enter");
  const proposal = page.getByRole("region", { name: "Tutor canvas proposal" });
  await expect(proposal).toBeVisible({ timeout: 180_000 });
  await expect(proposal).toContainText("Tutor reviewed CO2");
  await expect(page.locator(".canvas-object")).toContainText("Carbon dioxide");
  await page.getByRole("button", { name: "Apply tutor edit" }).click();
  await expect(page.locator(".canvas-object")).toContainText("Tutor reviewed CO2");
  await expect(page.locator(".top-actions .saved")).toHaveText("All changes saved");
  await page.reload();
  await expect(page.locator(".canvas-object")).toContainText("Tutor reviewed CO2");
  const boards = await (await request.get(`/api/canvases?course=${course.id}&lesson=${lesson.id}`)).json();
  const saved = await (await request.get(`/api/canvases/${boards[0].id}?course=${course.id}&lesson=${lesson.id}`)).json();
  const molecule = JSON.parse(saved.document).objects[0];
  expect(molecule.atoms[0].nonbondingElectrons).toBe(4);
  expect(molecule.resonanceForms[0].bonds[0].order).toBe(2);
  expect(shapes(JSON.parse(saved.document))).toEqual(drawing);
  await page.getByRole("combobox", { name: "Active lesson" }).selectOption(alternateLesson.id);
  await expect(page.locator(".canvas-object")).toHaveCount(0);
  await page.getByRole("combobox", { name: "Active lesson" }).selectOption(lesson.id);
  await expect(page.locator(".canvas-object")).toContainText("Tutor reviewed CO2");
  await page.getByRole("button", { name: "Link a document", exact: true }).click();
  await page.locator(".canvas-object-editor").getByRole("button", { name: "Done", exact: true }).click();
  await page.locator(".canvas-object").filter({ hasText: filename }).getByRole("button", { name: "Open source", exact: true }).click();
  await expect(page.getByRole("dialog", { name: filename })).toBeVisible();
  await page.getByRole("dialog", { name: filename }).getByRole("button", { name: "Close preview" }).click();
  await page.getByRole("button", { name: "Canvas", exact: true }).click();
  await page.getByRole("button", { name: "Link a note", exact: true }).click();
  await page.locator(".canvas-object-editor").getByRole("button", { name: "Done", exact: true }).click();
  await page.locator(".canvas-object").filter({ hasText: "Canvas note" }).getByRole("button", { name: "Open note", exact: true }).click();
  await page.locator(".notes-modal textarea").fill("Lewis structure review notes");
  await expect.poll(async () => (await (await request.get(`/api/notes?course=${course.id}&lesson=${lesson.id}`)).json())[0]?.body).toBe("Lewis structure review notes");
  expect(await (await request.get(`/api/notes?course=${course.id}&lesson=${alternateLesson.id}`)).json()).toEqual([]);
  expect(errors).toEqual([]);
});

test("canvas API rejects cross-course reads, writes, deletes and invalid lessons", async ({ request }) => {
  const { course, lesson } = await createCourseWithLesson(request);
  const otherCourse = await createCourse(request, `Second course ${Date.now()}`);
  const otherLesson = await createLesson(request, otherCourse.id, "Other lesson");
  const created = await request.post("/api/canvases", { data: { courseId: course.id, lessonId: lesson.id, name: "Scoped board", document: { version: 1, snapshot: { document: { store: {} } }, objects: [] } } });
  const id = (await created.json()).id as string;
  expect((await request.get(`/api/canvases/${id}?course=${otherCourse.id}&lesson=${lesson.id}`)).status()).toBe(404);
  expect((await request.delete(`/api/canvases/${id}?course=${otherCourse.id}&lesson=${lesson.id}`)).status()).toBe(404);
  const data = { id, courseId: otherCourse.id, lessonId: otherLesson.id, name: "Wrong scope", document: { version: 1, snapshot: { document: { store: {} } }, objects: [] } };
  expect((await request.post("/api/canvases", { data })).status()).toBe(409);
  expect((await request.post("/api/canvases", { data: { ...data, lessonId: "missing" } })).status()).toBe(400);
  expect((await request.post("/api/canvases", { data: { ...data, id: "invalid-document", document: { objects: [{}] } } })).status()).toBe(400);
});

test("legacy TXT API imports remain indexed and deletion stays synchronized", async ({ request }) => {
  const { course } = await createCourseWithLesson(request);
  const imported = await request.post("/api/documents", { data: { courseId: course.id, name: "legacy-route.txt", content: "Legacy route marker COMPAT-620." } });
  expect(imported.status()).toBe(201);
  const saved = await imported.json();
  expect(saved.status).toBe("indexed");
  const hits = await (await request.get(`/api/document-intelligence/search?course=${course.id}&q=COMPAT-620`)).json();
  expect(hits.results[0].documentId).toBe(saved.id);
  expect((await request.get(`/api/document-intelligence/documents/${saved.id}?course=${course.id}`)).status()).toBe(200);
  expect((await request.delete(`/api/document-intelligence/documents/${saved.id}?course=${course.id}`)).status()).toBe(200);
  expect(await (await request.get(`/api/documents?course=${course.id}`)).json()).toEqual([]);
  expect(await (await request.get(`/api/search?course=${course.id}&q=COMPAT-620`)).json()).toEqual([]);
});
